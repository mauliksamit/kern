#!/usr/bin/env python3
"""Generate results/facts.json and docs/FACTS.md from committed results.

Only verified numbers, each with the file it came from. Usage: python scripts/facts.py
"""
import glob
import json
import os
import re
import sys

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")


def load(rel):
    with open(os.path.join(ROOT, rel), encoding="utf-8") as f:
        return json.load(f)


def main() -> int:
    b = load("results/bench_M1024_N1024_K1024.json")
    med = {r["kernel"]: r for r in b["results"] if not r.get("failed")}
    v0, v6, cub = med["v0_naive"], med["v6_vec_transposed"], med["cublas"]
    corr = load("results/correctness_seed1234.json")
    san = {}
    for t in ("memcheck", "racecheck", "synccheck", "initcheck"):
        txt = open(os.path.join(ROOT, f"results/sanitizer/{t}.log"), encoding="utf-8", errors="replace").read()
        header = dict(re.findall(r"^# (\w+): (.*)$", txt, flags=re.M))
        summary = re.findall(r"(ERROR SUMMARY: .*|RACECHECK SUMMARY: .*)", txt)
        san[t] = {"summary": summary[-1] if summary else "missing", "pass_lines": len(re.findall(r" PASS$", txt, flags=re.M)),
                  "git_commit": header.get("git_commit", "?"), "build": header.get("build", "?")}
    ncu = load("results/ncu/ladder_M1024_N1024_K1024/summary.json")["kernels"]

    def m(k, metric):
        return ncu[k]["metrics"][metric]

    shapes = []
    for p in sorted(glob.glob(os.path.join(ROOT, "results", "bench_M*.json"))):
        d = load(os.path.relpath(p, ROOT))
        r = {x["kernel"]: x for x in d["results"] if not x.get("failed")}
        if "v6_vec_transposed" in r and "cublas" in r:
            shapes.append({"shape": f"{d['M']}x{d['N']}x{d['K']}", "v6_gflops": r["v6_vec_transposed"]["gflops"],
                           "cublas_gflops": r["cublas"]["gflops"],
                           "v6_pct_of_cublas": 100 * r["v6_vec_transposed"]["gflops"] / r["cublas"]["gflops"],
                           "source": os.path.relpath(p, ROOT).replace("\\", "/")})
    facts = {
        "generated_by": "scripts/facts.py",
        "device": b["device"], "driver": b["driver"], "compile_flags": b["compile_flags"],
        "bench_1024": {"v0_median_ms": v0["median_ms"], "v6_median_ms": v6["median_ms"], "cublas_median_ms": cub["median_ms"],
                       "v6_gflops": v6["gflops"], "cublas_gflops": cub["gflops"],
                       "v6_speedup_over_v0": v0["median_ms"] / v6["median_ms"],
                       "v6_pct_of_cublas": 100 * v6["gflops"] / cub["gflops"],
                       "bench_git_commit": b["git_commit"], "source": "results/bench_M1024_N1024_K1024.json"},
        "v6_vs_cublas_all_shapes": shapes,
        "correctness": {**corr, "pass_lines_per_sanitizer_log": min(v["pass_lines"] for v in san.values()),
                        "source": "results/correctness_seed1234.json + results/sanitizer/*.log"},
        "sanitizer": san,
        "ncu_1024": {
            "occupancy_theoretical_pct": {k: m(k, "sm__maximum_warps_per_active_cycle_pct") for k in ncu},
            "shared_ld_inst_v2_to_v4": [m("v2_tiled", "smsp__sass_inst_executed_op_shared_ld.sum"),
                                        m("v4_coarsened", "smsp__sass_inst_executed_op_shared_ld.sum")],
            "shared_ld_bank_conflicts_v5_v6": [m("v5_regtile", "l1tex__data_bank_conflicts_pipe_lsu_mem_shared_op_ld.sum"),
                                               m("v6_vec_transposed", "l1tex__data_bank_conflicts_pipe_lsu_mem_shared_op_ld.sum")],
            "fma_pipe_active_pct_v6_cublas": [m("v6_vec_transposed", "sm__pipe_fma_cycles_active.avg.pct_of_peak_sustained_active"),
                                              m("cublas", "sm__pipe_fma_cycles_active.avg.pct_of_peak_sustained_active")],
            "cublas_kernel": ncu["cublas"]["kernel_name"],
            "source": "results/ncu/ladder_M1024_N1024_K1024/summary.json"},
    }
    with open(os.path.join(ROOT, "results", "facts.json"), "w", encoding="utf-8") as f:
        json.dump(facts, f, indent=2)
        f.write("\n")
    bf = facts["bench_1024"]
    n = facts["ncu_1024"]
    lines = [
        "# Verified facts (generated — do not edit)", "",
        "Generated by `scripts/facts.py` from `results/`. Only verified numbers, each with its source file.",
        "",
        "| Fact | Value | Source |", "|---|---|---|",
        f"| Hardware / build | {b['device']}, driver {b['driver']}, flags `{b['compile_flags']}` | results/bench_M1024_N1024_K1024.json |",
        f"| SGEMM 1024³ medians | v0 {bf['v0_median_ms']:.4f} ms -> v6 {bf['v6_median_ms']:.4f} ms ({bf['v6_speedup_over_v0']:.2f}x); cuBLAS {bf['cublas_median_ms']:.4f} ms | results/bench_M1024_N1024_K1024.json |",
        f"| v6 vs cuBLAS at 1024³ | {bf['v6_gflops']:.1f} vs {bf['cublas_gflops']:.1f} GFLOPS ({bf['v6_pct_of_cublas']:.1f}% of cuBLAS) | results/bench_M1024_N1024_K1024.json |",
        f"| v6 vs cuBLAS, all {len(shapes)} shapes | {min(s['v6_pct_of_cublas'] for s in shapes):.1f}-{max(s['v6_pct_of_cublas'] for s in shapes):.1f}% of cuBLAS GFLOPS | results/bench_M*.json |",
        f"| Correctness gate | {corr['result']} (bad={corr['bad']}, seed {corr['seed']}); {min(v['pass_lines'] for v in san.values())} PASS lines in each sanitizer log | results/correctness_seed1234.json, results/sanitizer/ |",
        "| Compute Sanitizer (strict-IEEE build) | " + "; ".join(f"{t}: {v['summary']}" for t, v in san.items()) + " | results/sanitizer/*.log |",
        f"| Nsight Compute: v2 vs v4 theoretical occupancy | {n['occupancy_theoretical_pct']['v2_tiled']:.2f}% vs {n['occupancy_theoretical_pct']['v4_coarsened']:.2f}% (equal) | {n['source']} |",
        f"| Nsight Compute: shared-load instructions v2 -> v4 | {n['shared_ld_inst_v2_to_v4'][0]:,.0f} -> {n['shared_ld_inst_v2_to_v4'][1]:,.0f} | {n['source']} |",
        f"| Nsight Compute: shared-load bank conflicts v5 / v6 | {n['shared_ld_bank_conflicts_v5_v6'][0]:,.0f} / {n['shared_ld_bank_conflicts_v5_v6'][1]:,.0f} (identical) | {n['source']} |",
        f"| Nsight Compute: FMA pipe active, v6 vs cuBLAS | {n['fma_pipe_active_pct_v6_cublas'][0]:.2f}% vs {n['fma_pipe_active_pct_v6_cublas'][1]:.2f}% | {n['source']} |",
    ]
    with open(os.path.join(ROOT, "docs", "FACTS.md"), "w", encoding="utf-8") as f:
        f.write("\n".join(lines) + "\n")
    print("\n".join(lines))
    return 0


if __name__ == "__main__":
    sys.exit(main())
