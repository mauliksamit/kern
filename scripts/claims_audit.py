#!/usr/bin/env python3
"""Claims audit.

Checks that every numeric performance claim in README.md and docs/WRITEUP.md
traces to a file in
results/. Strategy (documented, approximate but honest):
  1. Extract all floating numbers from both files outside the results-table
     block that look like measurements (ms / GFLOPS / GB/s / % with nearby
     keyword). Protocol constants (the 100 ms
     single-run iteration rule, the 5% drift rule) are exempt by keyword.
  2. Require each to either (a) appear in some results/*.json within tolerance,
     or (b) be explicitly marked NOT RUN / estimated / TODO.
  3. Also verify the results table block matches scripts/generate_tables.py output.

Percentages must derive from two traced values within 1 percentage point,
either as a share (100*a/b) or as a relative change/drift (100*|a-b|/max(a,b)).
The 5% repeatability threshold ("drift") is a protocol constant,
not a measurement, and is exempt by keyword. Numbers inside a clearly labeled
analytical model (ideal/implied/analytical/extrapolation context) are exempt:
they are derived quantities, not measurements.
Exit 0 = audit passes. Exit 1 = untraced number found.
"""
import glob
import json
import os
import re
import sys

ROOT = os.path.join(os.path.dirname(__file__), "..")
README = os.path.join(ROOT, "README.md")
WRITEUP = os.path.join(ROOT, "docs", "WRITEUP.md")
RESULTS_GLOB = os.path.join(ROOT, "results", "*.json")
BEGIN = "<!-- RESULTS-BEGIN -->"
END = "<!-- RESULTS-END -->"


def load_numbers():
    nums = []
    for path in glob.glob(RESULTS_GLOB):
        try:
            with open(path, encoding="utf-8") as f:
                d = json.load(f)
        except Exception:
            continue
        for r in d.get("results", []):
            if r.get("failed", False) or r.get("skipped", False):
                continue  # failed/skipped backends carry no measurable value
            for key in ("median_ms", "min_ms", "p95_ms", "mean_ms", "gflops", "gbps"):
                if key in r:
                    nums.append(float(r[key]))
        # Estimated FP32 peak (TFLOPS) lives in the JSON metadata.
        if "peak_fp32_tflops_est" in d:
            nums.append(float(d["peak_fp32_tflops_est"]))
        # ML transformer JSON: measured torch medians/GFLOPS per config.
        for s in d.get("shapes", []):
            for cfg in ("eager", "compiled", "tf32_allowed"):
                r = s.get(cfg, {})
                if isinstance(r, dict):
                    for key in ("median_ms", "min_ms", "p95_ms", "mean_ms", "gflops"):
                        if key in r:
                            nums.append(float(r[key]))
    # Nsight Compute ladder summaries (generated by scripts/ncu_summary.py):
    # counter values and their defined derived ratios are traced evidence.
    for path in glob.glob(os.path.join(ROOT, "results", "ncu", "*", "summary.json")):
        with open(path, encoding="utf-8") as f:
            d = json.load(f)
        for rec in d.get("kernels", {}).values():
            for group in ("metrics", "derived"):
                for v in rec.get(group, {}).values():
                    if isinstance(v, (int, float)):
                        nums.append(float(v))
    return nums



def comparable_groups():
    """Groups of values that may legitimately be divided by each other:
    the same metric for the same GEMM shape (bench, ML and C++ harness files),
    the same metric for the same kernel across shapes (scaling claims), the
    estimated peak alongside GFLOPS, and the same ncu counter across kernels.
    Speedups and percentages must be ratios WITHIN one group; a free search
    over all pairs of ~1000 stored values would accept almost any number."""
    from collections import defaultdict
    groups = defaultdict(list)
    for path in glob.glob(RESULTS_GLOB):
        try:
            with open(path, encoding="utf-8") as f:
                d = json.load(f)
        except Exception:
            continue
        if "results" in d and "M" in d:
            shape = (d["M"], d["N"], d["K"])
            for r in d["results"]:
                if r.get("failed") or r.get("skipped"):
                    continue
                for key in ("median_ms", "min_ms", "gflops"):
                    if key in r:
                        groups[("shape", shape, key)].append(float(r[key]))
                        groups[("kernel", r.get("kernel"), key)].append(float(r[key]))
            if "peak_fp32_tflops_est" in d:
                groups[("shape", shape, "gflops")].append(1000.0 * float(d["peak_fp32_tflops_est"]))
        for sh in d.get("shapes", []):
            shape = (sh.get("M"), sh.get("N"), sh.get("K"))
            for cfg in ("eager", "tf32_allowed"):
                r = sh.get(cfg)
                if isinstance(r, dict):
                    for key in ("median_ms", "gflops"):
                        if key in r:
                            groups[("shape", shape, key)].append(float(r[key]))
    for path in glob.glob(os.path.join(ROOT, "results", "ncu", "*", "summary.json")):
        with open(path, encoding="utf-8") as f:
            d = json.load(f)
        for rec in d.get("kernels", {}).values():
            for metric, v in rec.get("metrics", {}).items():
                if isinstance(v, (int, float)):
                    groups[("ncu", path, metric)].append(float(v))
    return groups


def derived_values(groups):
    pct, ratio = set(), set()
    for vals in groups.values():
        for a in vals:
            for b in vals:
                if not b:
                    continue
                r = a / b
                ratio.add(r)
                pct.update((100.0 * r, 100.0 * (r - 1.0), 100.0 * (1.0 - r),
                            100.0 * abs(a - b) / max(abs(a), abs(b)) if max(abs(a), abs(b)) else 0.0))
    return sorted(pct), sorted(ratio)


def _close(val, cands, dec):
    import bisect
    tol = 0.5 * 10 ** -dec + 1e-9
    i = bisect.bisect_left(cands, val - tol)
    return i < len(cands) and cands[i] <= val + tol

CHECKED = []


def check_text(text, label, traced, failures, derived):
    """A number with a unit must equal a stored value within its printed
    precision (TFLOPS may match GFLOPS / 1000). A percentage or a speedup
    (x / ×) may instead equal a ratio WITHIN one comparable group (see
    comparable_groups); never a ratio of two arbitrary stored values.

    Limitation, stated plainly: this guarantees a percentage/speedup is
    DERIVABLE from two comparable measurements, not that it is the pair the
    sentence means. With many kernels and shapes per group, a one-decimal
    percentage can match some comparable pair by coincidence (a made-up
    "12.3%" passed a probe; a made-up "9.37x" failed)."""
    pct, ratio = derived
    direct = sorted(set(traced))
    tflops = sorted(set(t / 1000.0 for t in traced))
    pattern = re.compile(r"(\d+\.\d+|\d+)\s*(ms|GFLOPS|GB/s|TFLOPS|%|×(?![\d])|x(?![\w]))")
    for m in pattern.finditer(text):
        raw, unit = m.group(1), m.group(2)
        val = float(raw)
        dec = len(raw.split(".")[1]) if "." in raw else 0
        # Skip obvious non-claims: years, versions, tile sizes, counts.
        start = max(0, m.start() - 60)
        ctx = text[start:m.end() + 40]
        if re.search(r"NOT RUN|TODO|e\.g\.|for example|version|CUDA \d|sm_\d|drift|exceeds", ctx, re.I):
            continue
        if re.search(r"TILE", ctx):  # the TILE constant (case-sensitive), not prose about tiles
            continue
        # Derived quantities inside a labeled analytical model are not measurements.
        if re.search(r"ideal|implied|analytical|extrapolat|upper-bound|roofline", ctx, re.I):
            continue
        if "NOT RUN" in text[max(0, m.start() - 200):m.end()]:
            continue
        if unit in ("×", "x"):
            ok = _close(val, ratio, dec) or _close(val, direct, dec)
        elif unit == "%":
            ok = _close(val, direct, dec) or _close(val, pct, dec)
        elif unit.upper() == "TFLOPS":
            ok = _close(val, direct, dec) or _close(val, tflops, dec)
        else:
            ok = _close(val, direct, dec)
        CHECKED.append((label, val, unit))
        if not ok:
            failures.append((label, val, unit, ctx.strip().replace("\n", " ")[:120]))


def main():
    with open(README, encoding="utf-8") as f:
        readme_text = f.read()
    with open(WRITEUP, encoding="utf-8") as f:
        wu_text = f.read()
    # Remove the generated table block: those numbers are traced by construction.
    if BEGIN in readme_text and END in readme_text:
        pre, _, rest = readme_text.partition(BEGIN)
        _, _, post = rest.partition(END)
        readme_body = pre + post
    else:
        readme_body = readme_text
    traced = load_numbers()
    failures = []
    derived = derived_values(comparable_groups())
    check_text(readme_body, "README", traced, failures, derived)
    check_text(wu_text, "WRITEUP", traced, failures, derived)
    # Table freshness: regenerate and compare.
    sys.path.insert(0, os.path.join(ROOT, "scripts"))
    try:
        import importlib.util
        spec = importlib.util.spec_from_file_location(
            "gen", os.path.join(ROOT, "scripts", "generate_tables.py"))
        gen = importlib.util.module_from_spec(spec)
        spec.loader.exec_module(gen)
        table = gen.render(gen.load_rows())
        if table.strip() not in readme_text:
            print("AUDIT NOTE: results table block is stale "
                  "(run python scripts/generate_tables.py --write).")
            # Stale table is a failure only when results exist.
            if traced:
                failures.append(("README", "stale-table", "", "regenerate README table"))
    except Exception as e:
        print(f"AUDIT WARNING: could not verify table freshness: {e}")

    if failures:
        print("CLAIMS AUDIT FAILED: untraced numbers in README/WRITEUP (not in results/*.json):")
        for label, val, unit, ctx in failures:
            print(f"  [{label}] {val} {unit}  ...{ctx}...")
        print("Fix: run the bench to produce results/*.json, regenerate the table, "
              "or mark the claim NOT RUN.")
        return 1
    n_sp = sum(1 for c in CHECKED if c[2] in ("x", "×"))
    n_pct = sum(1 for c in CHECKED if c[2] == "%")
    print(f"CLAIMS AUDIT PASSED ({len(CHECKED)} claims checked: {n_pct} percentages, {n_sp} speedups; "
          f"{len(traced)} traced values in results/*.json).")
    return 0


if __name__ == "__main__":
    sys.exit(main())
